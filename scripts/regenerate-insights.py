#!/usr/bin/env python3
"""Clear the old insights and regenerate three per source.

Run from the repo root with the stack up:

    set -a && . ./.env && set +a
    export SURREAL_URL="ws://127.0.0.1:8108/rpc"
    .venv/bin/python scripts/regenerate-insights.py            # show the plan
    .venv/bin/python scripts/regenerate-insights.py --apply    # do it

What it does, in order, and why in that order
--------------------------------------------
1. **Cancel the held and failed transformation jobs.** They were queued against
   the *old* prompts. Left alone they would run and write machine-facing SPR
   summaries and topic-filtered insights — the exact text this run exists to
   replace — and because the worker is one-at-a-time on this device they would
   also sit in front of the 48 new jobs. Cancelling is not deleting: the rows
   stay, with their status, so the history of what was attempted survives.

2. **Delete every insight.** Not the three types being regenerated — all of
   them, including Paper Analysis and Table of Contents, because they were
   generated by the same stock prompts and the user asked for a clean set of
   three per source. Sources keep their text, their embeddings and their ids.

3. **Raise the window.** One at a time on a device whose pool is a third of
   the model's is the pre-per-model answer. Concurrent transformations share
   one resident model now, so three cost one model plus three small workers.

4. **Queue through the real endpoint.** `POST /processing/ensure-insights`
   rather than a reimplementation, so the dedup against (source,
   transformation) and against already-queued work is the same code that runs
   in production. A hand-rolled version of that logic is how twin insights
   happen.

What it deliberately does not do
-------------------------------
It does not touch `source` rows, `asset` blobs, or embeddings. A regeneration
that can lose the source material is not a regeneration.
"""

from __future__ import annotations

import argparse
import asyncio
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

WANTED = ["Dense Summary", "Key Insights", "Reflection Questions"]
WINDOW = 3


async def main(apply: bool) -> int:
    from open_notebook.database.repository import repo_query

    async def q(sql, params=None):
        return await repo_query(sql, params)

    transforms = await q(
        "SELECT id, title FROM transformation WHERE title IN $titles",
        {"titles": WANTED},
    )
    titles = {str(r["title"]): str(r["id"]) for r in transforms}
    missing = [t for t in WANTED if t not in titles]
    if missing:
        print(f"ERROR: transformations not in the database: {missing}", file=sys.stderr)
        return 1

    sources = await q("SELECT id, title FROM source")
    sources.sort(key=lambda s: str(s.get("title") or ""))
    insights = await q(
        "SELECT insight_type, count() AS n FROM source_insight GROUP BY insight_type"
    )
    pending = await q(
        "SELECT name, status, count() AS n FROM command "
        "WHERE status IN ['held', 'failed'] GROUP BY name, status ORDER BY n DESC"
    )

    print(f"  sources          {len(sources)}")
    print(f"  transformations  {len(titles)}  ({', '.join(WANTED)})")
    print(f"  jobs to queue    {len(sources) * len(titles)}")
    print()
    print("  insights to delete:")
    for row in insights:
        print(f"    - {row.get('insight_type')}: {row.get('n')}")
    print()
    print("  commands to cancel (queued against the old prompts):")
    for row in pending:
        print(f"    - {row.get('name')} / {row.get('status')}: {row.get('n')}")

    if not apply:
        print()
        print("  Nothing changed. Re-run with --apply.")
        return 0

    print()
    print("  cancelling work that would run against the old prompts...")
    # Only `held` and `new`, deliberately. Those two would execute and write the
    # old machine-facing text ahead of the 48 new jobs. `failed` rows are left
    # alone: nothing retries them without an explicit retry call, the endpoint's
    # dedup does not count them as pending, and rewriting 140 rows of failure
    # history changes the record of what was attempted for no benefit.
    for status in ("held", "new"):
        await q(
            "UPDATE command SET status='canceled' WHERE name IN "
            "['run_transformation', 'create_insight', 'embed_insight'] "
            f"AND status='{status}'"
        )
    still = await q(
        "SELECT count() AS n FROM command "
        "WHERE status IN ['held', 'new'] AND name IN "
        "['run_transformation', 'create_insight', 'embed_insight'] GROUP ALL"
    )
    print(
        f"    -> {(still[0].get('n') if still else 0)} still queued against the old prompts"
    )

    print("  deleting every insight, one type at a time...")
    # Scoped per type rather than `DELETE source_insight`, because the
    # repository refuses an unscoped delete outright — correctly. There is an
    # `OPEN_NOTEBOOK_ALLOW_BULK_DELETE` escape hatch, and reaching for it here
    # would be trading a check that exists for one line of convenience. One
    # statement per type also reports what went, so a partial run is visible.
    deleted_total = 0
    for row in insights:
        insight_type = str(row.get("insight_type"))
        await q(
            "DELETE source_insight WHERE insight_type = $t",
            {"t": insight_type},
        )
        n = int(row.get("n") or 0)
        deleted_total += n
        print(f"    - {insight_type}: {n}")
    after = await q("SELECT count() AS n FROM source_insight GROUP ALL")
    remaining = int(after[0].get("n")) if after else 0
    print(f"    -> {deleted_total} deleted, {remaining} remain")
    if remaining:
        print(
            f"    WARNING: {remaining} insights of a type not listed above survived. "
            "They were not in the plan and were not deleted.",
            file=sys.stderr,
        )

    print("  raising the window and queueing through the API...")
    import httpx

    from open_notebook.scheduler.dispatcher import read_window, write_window

    # Address the file the *worker* reads, not the one this process would pick.
    # `_throttle_file()` chooses `/app/data/throttle.conf` when `/.dockerenv`
    # exists and `.env` otherwise, and it decides that from the running
    # process's own view. Run from the host, there is no `/.dockerenv`, so a
    # plain `write_window` lands in `.env` — which the container never reads.
    # The first run of this script reported `window 2 -> 3` and the live API
    # still answered 1, because it had written to the wrong file.
    #
    # So the path is stated here rather than inferred. The window is a hot
    # setting read fresh each pass, which is why it lives in a file at all and
    # why getting the file right matters more than getting the number right.
    throttle_file = Path(os.environ.get("THROTTLE_FILE", "notebook_data/throttle.conf"))
    os.environ["THROTTLE_FILE"] = str(throttle_file)
    before_window = read_window()
    after_window = write_window(WINDOW)
    print(f"    window {before_window} -> {after_window}   ({throttle_file})")

    password = os.getenv("OPEN_NOTEBOOK_PASSWORD", "")
    if not password:
        print(
            "ERROR: OPEN_NOTEBOOK_PASSWORD is unset, cannot authenticate.",
            file=sys.stderr,
        )
        return 1

    async with httpx.AsyncClient(timeout=120.0) as client:
        headers = {"Authorization": f"Bearer {password}"}
        api = os.getenv("OPEN_NOTEBOOK_API_URL", "http://127.0.0.1:5055")

        queued = await client.post(
            f"{api}/api/processing/ensure-insights",
            json={"transformation_ids": [titles[t] for t in WANTED]},
            headers=headers,
        )
        print(f"    queue    -> {queued.status_code}")
        try:
            print(f"    {queued.json()}")
        except ValueError:
            print(f"    {queued.text[:400]}")

    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--apply", action="store_true", help="do it; otherwise just show the plan"
    )
    args = parser.parse_args()
    raise SystemExit(asyncio.run(main(args.apply)))
